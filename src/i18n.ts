const apiErrorLookup = new Map(apiErrorRows.map(([code, ka, ru, en]) => [code, { ka, ru, en }]));

export function localizeApiError(lang: Language, code: string | undefined, message: string): string {
  const byCode = code ? apiErrorLookup.get(code)?.[lang] : undefined;
  if (byCode) return byCode;
  const known = localizeInlineText(lang, message);
  if (known !== message) return known;
  const georgian = /[\u10A0-\u10FF]/.test(message);
  const russian = /[\u0400-\u04FF]/.test(message);
  if ((georgian && lang !== 'ka') || (russian && lang !== 'ru') || (!georgian && !russian && lang !== 'en')) {
    return lang === 'ka' ? 'მოთხოვნის შესრულება ვერ მოხერხდა. სცადეთ მოგვიანებით.' : lang === 'ru' ? 'Не удалось выполнить запрос. Попробуйте позже.' : 'The request could not be completed. Please try again later.';
  }
  return message;
}

export function localizeInlineText(lang: Language, text: string): string {
  const leading = text.match(/^\s*/)?.[0] ?? '';
  const trailing = text.match(/\s*$/)?.[0] ?? '';
  const normalized = text.trim().replace(/\s+/g, ' ');
  const translated = inlineTextLookup.get(normalized)?.[lang] ?? dynamicInlineText(lang, normalized);
  return translated === normalized ? text : `${leading}${translated}${trailing}`;
}

const dateLocale: Record<Language, string> = { ka: 'ka-GE', ru: 'ru-RU', en: 'en-US' };

export function formatLocalizedDate(lang: Language, value: string | number | Date, options?: Intl.DateTimeFormatOptions): string {
  return new Date(value).toLocaleDateString(dateLocale[lang], options);
}

export function formatLocalizedDateTime(lang: Language, value: string | number | Date, options?: Intl.DateTimeFormatOptions): string {
  return new Date(value).toLocaleString(dateLocale[lang], options);
}

export function formatLocalizedTime(lang: Language, value: string | number | Date, options?: Intl.DateTimeFormatOptions): string {
  return new Date(value).toLocaleTimeString(dateLocale[lang], options);
}

export function formatCraftsmanCount(lang: Language, count: number): string {
  if (lang === 'ka') return `${count} ხელოსანი`;
  if (lang === 'en') return `${count} ${count === 1 ? 'craftsman' : 'craftsmen'}`;
  const lastTwo = count % 100;
  const last = count % 10;
  const noun = lastTwo >= 11 && lastTwo <= 14 ? 'мастеров' : last === 1 ? 'мастер' : last >= 2 && last <= 4 ? 'мастера' : 'мастеров';
  return `${count} ${noun}`;
}

const translatableProps = ['alt', 'aria-label', 'placeholder', 'title'] as const;

export function localizeTree(lang: Language, node: React.ReactNode): React.ReactNode {
  if (typeof node === 'string') return localizeInlineText(lang, node);
  if (Array.isArray(node)) return node.map((child) => localizeTree(lang, child));
  if (!React.isValidElement(node)) return node;

  const element = node as React.ReactElement<Record<string, unknown>>;
  if (element.type !== React.Fragment && typeof element.type !== 'string') return element;

  const props: Record<string, unknown> = { ...element.props };
  if ('children' in props) props.children = localizeTree(lang, props.children as React.ReactNode);
  for (const prop of translatableProps) {
    if (typeof props[prop] === 'string') props[prop] = localizeInlineText(lang, props[prop] as string);
  }
  return React.cloneElement(element, props);
}

